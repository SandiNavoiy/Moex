def detect_phase(score: int) -> str:
    if score == 30:
        return "Восстановление"
    if 20 <= score <= 29:
        return "Пик"
    if 10 <= score <= 19:
        return "Замедление"
    return "Рецессия"


@app.route("/", methods=["GET", "POST"])
def index():
    if request.method == "POST":
        total_score = 0
        for q in QUESTIONS:
            answer = request.form.get(f"q{q['id']}")
            total_score += SCORES.get(answer, 0)

        phase = detect_phase(total_score)

        return render_template(
            "result.html",
            score=total_score,
            phase=phase,
            recommendation=RECOMMENDATIONS[phase]
        )

    return render_template("test.html", questions=QUESTIONS)


