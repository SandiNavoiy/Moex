def ask_question(q):
    print("\n" + q["text"])
    for k, v in q["options"].items():
        print(f"  {k} — {v}")

    while True:
        answer = input("Ваш выбор (A / B / C / D): ").strip().upper()
        if answer in SCORES:
            return SCORES[answer]
        print("Введите A, B, C или D.")


def detect_phase(score):
    for r, phase in PHASE_RANGES.items():
        if score in r:
            return phase
    return "Неопределено"


def run_test():
    total = 0
    print("Тест определения фазы экономического цикла")

    for q in QUESTIONS:
        total += ask_question(q)

    phase = detect_phase(total)

    print("\nРезультат")
    print("=" * 40)
    print(f"Баллы: {total} из 30")
    print(f"Фаза цикла: {phase}")

    if phase in RECOMMENDATIONS:
        print("\nРекомендации:")
        print(RECOMMENDATIONS[phase])


if __name__ == "__main__":
    run_test()
